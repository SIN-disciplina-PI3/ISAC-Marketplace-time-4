-- ==========================================================
-- V1: Criação das tabelas do ISAC Marketplace
-- Compatível com PostgreSQL e H2 (modo PostgreSQL)
-- ==========================================================

CREATE TABLE IF NOT EXISTS categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    ativa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS lojas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_fantasia VARCHAR(150) NOT NULL,
    documento VARCHAR(20) UNIQUE,
    tipo_documento VARCHAR(10),
    categoria VARCHAR(100),
    telefone_whatsapp VARCHAR(20) NOT NULL UNIQUE,
    email VARCHAR(150),
    bairro VARCHAR(100) NOT NULL,
    endereco VARCHAR(255),
    plano VARCHAR(20) NOT NULL DEFAULT 'GRATUITO',
    status_assinatura VARCHAR(20) NOT NULL DEFAULT 'INATIVA',
    data_vencimento_assinatura TIMESTAMP,
    data_cadastro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    papel VARCHAR(20) NOT NULL,
    loja_id BIGINT,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_usuarios_loja FOREIGN KEY (loja_id) REFERENCES lojas(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS anuncios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loja_id BIGINT NOT NULL,
    categoria_id BIGINT,
    titulo VARCHAR(150) NOT NULL,
    descricao TEXT,
    preco NUMERIC(10, 2) NOT NULL,
    bairro VARCHAR(100) NOT NULL,
    tipo VARCHAR(20) NOT NULL DEFAULT 'PRODUTO',
    foto_url VARCHAR(500),
    status VARCHAR(30) NOT NULL DEFAULT 'ATIVO',
    disponivel BOOLEAN NOT NULL DEFAULT TRUE,
    destaque BOOLEAN NOT NULL DEFAULT FALSE,
    data_publicacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_expiracao TIMESTAMP NOT NULL,
    aviso_expiracao_enviado BOOLEAN NOT NULL DEFAULT FALSE,
    motivo_rejeicao TEXT,
    CONSTRAINT fk_anuncios_loja FOREIGN KEY (loja_id) REFERENCES lojas(id) ON DELETE CASCADE,
    CONSTRAINT fk_anuncios_categoria FOREIGN KEY (categoria_id) REFERENCES categorias(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS pagamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loja_id BIGINT NOT NULL,
    valor NUMERIC(10, 2) NOT NULL,
    referencia_ciclo VARCHAR(50),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    confirmado_em TIMESTAMP,
    confirmado_por VARCHAR(100),
    CONSTRAINT fk_pagamentos_loja FOREIGN KEY (loja_id) REFERENCES lojas(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS conversas_whatsapp (
    telefone_hash VARCHAR(64) PRIMARY KEY,
    etapa VARCHAR(50) NOT NULL,
    dados_parciais TEXT,
    atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS buscas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    termo VARCHAR(255) NOT NULL,
    canal VARCHAR(20) NOT NULL,
    resultados INT NOT NULL DEFAULT 0,
    telefone_hash VARCHAR(64),
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS eventos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL,
    descricao TEXT,
    local VARCHAR(200) NOT NULL,
    data_inicio TIMESTAMP NOT NULL,
    data_fim TIMESTAMP,
    publicado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS conteudos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chave VARCHAR(50) NOT NULL UNIQUE,
    titulo VARCHAR(200) NOT NULL,
    corpo_markdown TEXT NOT NULL,
    atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS importacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    arquivo_nome VARCHAR(255) NOT NULL,
    total_mensagens INT NOT NULL DEFAULT 0,
    total_candidatos INT NOT NULL DEFAULT 0,
    status VARCHAR(30) NOT NULL DEFAULT 'CONCLUIDO',
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS anuncios_importados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    importacao_id BIGINT NOT NULL,
    autor_nome VARCHAR(150),
    telefone VARCHAR(30),
    texto_original TEXT NOT NULL,
    titulo_sugerido VARCHAR(150),
    preco_sugerido NUMERIC(10, 2),
    categoria_sugerida VARCHAR(100),
    data_mensagem TIMESTAMP,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDENTE_REVISAO',
    anuncio_id BIGINT,
    CONSTRAINT fk_candidatos_importacao FOREIGN KEY (importacao_id) REFERENCES importacoes(id) ON DELETE CASCADE,
    CONSTRAINT fk_candidatos_anuncio FOREIGN KEY (anuncio_id) REFERENCES anuncios(id) ON DELETE SET NULL
);
