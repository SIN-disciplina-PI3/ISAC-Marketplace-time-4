-- Fase 5: Importador de exportacoes de grupo WhatsApp

CREATE TABLE importacoes_whatsapp (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_arquivo VARCHAR(255) NOT NULL,
    tamanho_bytes BIGINT NOT NULL,
    total_mensagens INTEGER NOT NULL DEFAULT 0,
    total_candidatos INTEGER NOT NULL DEFAULT 0,
    aprovados INTEGER NOT NULL DEFAULT 0,
    descartados INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(30) NOT NULL DEFAULT 'PROCESSANDO',
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processado_em TIMESTAMP
);

CREATE TABLE candidatos_anuncio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    importacao_id BIGINT NOT NULL REFERENCES importacoes_whatsapp(id) ON DELETE CASCADE,
    remetente_hash VARCHAR(64) NOT NULL,
    data_mensagem TIMESTAMP,
    texto_original TEXT NOT NULL,
    titulo_sugerido VARCHAR(255),
    descricao_sugerida TEXT,
    preco_sugerido NUMERIC(10, 2),
    status VARCHAR(30) NOT NULL DEFAULT 'PENDENTE_REVISAO',
    anuncio_id BIGINT REFERENCES anuncios(id) ON DELETE SET NULL,
    revisado_em TIMESTAMP
);

CREATE INDEX idx_candidatos_importacao ON candidatos_anuncio(importacao_id);
CREATE INDEX idx_candidatos_status ON candidatos_anuncio(status);
